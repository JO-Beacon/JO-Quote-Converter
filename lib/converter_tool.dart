/// The text conversion tools offered by the application.
enum ConverterTool {
  /// Converts straight English quotation marks into Chinese curly quotes.
  quote,

  /// Converts half-width English commas into the Chinese full-width comma.
  comma,

  /// Converts half-width English colons into the Chinese full-width colon.
  colon,

  /// Converts half-width English exclamation marks into the Chinese full-width
  /// exclamation mark.
  exclamation,

  /// Converts half-width English question marks into the Chinese full-width
  /// question mark.
  question,

  /// Converts half-width English semicolons into the Chinese full-width
  /// semicolon.
  semicolon,
}
